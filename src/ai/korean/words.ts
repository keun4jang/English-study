/** 모든 표제어를 긴 것부터 (부분 일치로 짧은 단어가 먼저 잡히는 것을 막는다) */
export function sortedKeys(index: Map<string, KoNoun>): string[] {
  return [...index.keys()].sort((a, b) => b.length - a.length);
}

/** 검색용 통합 사전 (긴 표제어가 먼저 걸리도록 정렬해 둔다) */
function indexOf(list: KoNoun[]): Map<string, KoNoun> {
  const map = new Map<string, KoNoun>();
  for (const word of list) {
    map.set(word.ko, word);
    for (const alt of word.alt ?? []) map.set(alt, word);
  }
  return map;
}

